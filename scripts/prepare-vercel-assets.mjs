import {
  cpSync,
  existsSync,
  lstatSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const markerName = ".structr-generated-assets";
const markerValue = "Generated by prepare-vercel-assets.mjs; do not edit.\n";

/** Validate the complete input before replacing a previous generated output. */
function rejectLinks(directory) {
  if (lstatSync(directory).isSymbolicLink())
    throw new Error("Refusing symbolic asset paths");
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink())
      throw new Error("Refusing symbolic asset paths");
    if (entry.isDirectory()) rejectLinks(join(directory, entry.name));
    else if (!entry.isFile())
      throw new Error("Refusing non-regular asset files");
  }
}

/** @param {string} root */
export function prepareVercelAssets(root) {
  const source = resolve(root, "dist/public");
  const target = resolve(root, "public");
  const entry = join(source, "index.html");
  if (!existsSync(entry) || !lstatSync(entry).isFile())
    throw new Error("Missing compiled index.html");
  if (lstatSync(resolve(root, "dist")).isSymbolicLink())
    throw new Error("Refusing symbolic asset paths");
  rejectLinks(source);
  // lstat also detects dangling output links, which existsSync follows.
  let targetExists = false;
  try {
    const stat = lstatSync(target);
    targetExists = true;
    if (stat.isSymbolicLink())
      throw new Error("Refusing symbolic output paths");
    const marker = join(target, markerName);
    if (
      !stat.isDirectory() ||
      !existsSync(marker) ||
      lstatSync(marker).isSymbolicLink() ||
      readFileSync(marker, "utf8") !== markerValue
    ) {
      throw new Error(
        "Existing public folder was not generated by this builder"
      );
    }
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (targetExists) rmSync(target, { recursive: true });
  cpSync(source, target, { recursive: true, dereference: false });
  writeFileSync(join(target, markerName), markerValue);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  prepareVercelAssets(process.cwd());
  console.log("Prepared compiled frontend assets for the native Express host.");
}
